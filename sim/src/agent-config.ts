/**
 * Turns the plant description into a Khorde agent configuration: one file
 * holding both REST agents, keyed by agent name, as the control plane's
 * "Upload configuration" expects.
 */

import { stringify } from "yaml";
import { driverPath, type AgentName, type Plant } from "./plant.ts";

export const SCHEMA_URL = "https://schemas.khorde.io/v1/agent-config.yaml";

export interface AgentConfig {
  type: "client";
  protocol: "rest";
  measurements: Record<string, unknown>[];
  alarms: Record<string, unknown>[];
  commands: Record<string, unknown>[];
  interlocks: Record<string, unknown>[];
}

export function agentConfigs(plant: Plant): Record<AgentName, AgentConfig> {
  const out = {} as Record<AgentName, AgentConfig>;
  for (const agent of Object.values(plant.agents)) {
    out[agent] = {
      type: "client",
      protocol: "rest",
      measurements: plant.points
        .filter((p) => p.agent === agent)
        .map((p) => ({
          name: p.name,
          type: p.type,
          store: p.store,
          equipment: p.equipment,
          tags: p.tags,
          driver: { type: p.type, path: driverPath(p.equipment, p.name) },
        })),
      alarms: plant.alarms.filter((a) => a.agent === agent).map((a) => a.config),
      commands: plant.commands
        .filter((c) => c.agent === agent)
        .map((c) => ({
          name: c.name,
          equipment: c.equipment,
          driver:
            c.type === "discrete"
              ? { type: "discrete", value: c.value ?? 1, path: driverPath(c.equipment, c.name) }
              : { type: "analogical", path: driverPath(c.equipment, c.name) },
          ...(c.interlock ? { interlock: { key: c.interlock } } : {}),
        })),
      interlocks: plant.interlocks
        .filter((i) => i.agent === agent)
        .map((i) => ({ key: i.key, description: i.description, expression: i.expression })),
    };
  }
  return out;
}

export function agentConfigYaml(plant: Plant): string {
  const header = [
    `# yaml-language-server: $schema=${SCHEMA_URL}`,
    "# Generated by `npm run gen -w @khorde/demo-plant` from sim/src/plant.ts. Do not edit by hand.",
    `# Ventos da Serra · ${plant.turbines.length} turbines (${plant.turbinesPerFeeder} per feeder)`,
    "",
  ].join("\n");
  return header + stringify(agentConfigs(plant), { lineWidth: 0 });
}
